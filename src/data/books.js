export function fetchBooks() {
  return new Promise((resolve) => {
    setTimeout(() => resolve(books), DELAY);
  });
}

export function fetchBookById(id) {
  return new Promise((resolve) => {
    setTimeout(() => resolve(books.find((book) => book.id === Number(id)) || null), DELAY);
  });
}
